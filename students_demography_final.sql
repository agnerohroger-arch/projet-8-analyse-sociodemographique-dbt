
-- ENRICHED MODEL : enrichissement avec la population

CREATE OR REPLACE VIEW DEMO_DB.PUBLIC.STUDENTS_DEMOGRAPHY_FINAL AS
SELECT
    S.USER_ID,
    S.AGE_GROUP,
    S.GENDER,
    S.REGION,
    S.YEAR_PATH_STARTED,
    P.POPULATION
FROM DEMO_DB.PUBLIC.STUDENTS_CLEAN S
LEFT JOIN DEMO_DB.PUBLIC.POPULATION_CLEAN P
    ON S.REGION = P.REGION;
